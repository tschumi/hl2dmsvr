#!/bin/bash

GAME_DIR="/steam/hl2dm"

# Install or update the game; retry because steamcmd fails sporadically ("Missing configuration")
for i in 1 2 3; do
    /steam/steamcmd_linux/steamcmd.sh +force_install_dir "$GAME_DIR" +login anonymous +app_update 232370 +quit && break
    echo "steamcmd failed (attempt $i)"
    if [[ $i == 3 ]]; then
        if [[ -x "$GAME_DIR/srcds_run" ]]; then
            echo "Update failed, starting existing installation"
        else
            echo "Installation failed, exiting"
            exit 1
        fi
    fi
    sleep 5
done

# Copy own configs, plugins etc. over the game files (overwrites changes made inside the volume)
cp -a /steam/dist/. "$GAME_DIR/"

# Download missing maps
wget -P "$GAME_DIR/hl2mp/maps/" --no-verbose --no-clobber -i "$GAME_DIR/hl2mp/maps/maps.txt" --base="$CONTENT_SERVER/maps/" \
    || echo "Some maps could not be downloaded"

cd "$GAME_DIR" || exit 1

[[ -z $MAP ]] && MAP="dm_underpass"
[[ -z $MAXPLAYERS ]] && MAXPLAYERS=8

if [[ $PUBLIC == 1 ]]
then
    SV_LAN="+sv_lan 0"
else
    SV_LAN="+sv_lan 1"
fi

# startup.cfg (defaults) and env.cfg (overrides) are executed once at start, not on map change,
# so changes via rcon persist until restart
ENV_CFG="/steam/hl2dm/hl2mp/cfg/env.cfg"

# Source cfg values can't contain double quotes, so strip them
cfg_value() {
    printf '%s' "${1//\"/}"
}

# Write settings from environment variables to env.cfg (regenerated on every start)
{
    echo "// generated by start.sh from environment variables - do not edit"
    [[ -n $SV_HOSTNAME ]]    && echo "hostname \"$(cfg_value "$SV_HOSTNAME")\""
    [[ -n $SV_PASSWORD ]]    && echo "sv_password \"$(cfg_value "$SV_PASSWORD")\""
    [[ -n $RCON_PASSWORD ]]  && echo "rcon_password \"$(cfg_value "$RCON_PASSWORD")\""
    [[ -n $SV_DOWNLOADURL ]] && echo "sv_downloadurl \"$(cfg_value "$SV_DOWNLOADURL")\""
    [[ -n $WINLIMIT ]]       && echo "mp_winlimit \"$(cfg_value "$WINLIMIT")\""
    [[ -n $MAPCYCLE_FILE ]]  && echo "mapcyclefile \"$(cfg_value "$MAPCYCLE_FILE")\""
} > "$ENV_CFG"

exec ./srcds_run -game hl2mp $SV_LAN -ip 0.0.0.0 +exec startup.cfg +exec env.cfg +exec server.cfg +map $MAP -maxplayers $MAXPLAYERS
